"""Docs as code: regenerate the KPI dictionary and the data dictionary from the code itself,
so documentation can never drift from what the pipeline actually builds."""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd
import yaml

from ..config import ROOT
from ..kpi.semantic import kpi_table, load_kpis
from ..pipeline.runner import discover_models, topo_sort

DOCS = ROOT / "docs"
GLOSSARY = ROOT / "config" / "glossary.yaml"


def _header_comment(sql: str) -> str:
    lines = []
    for line in sql.splitlines():
        s = line.strip()
        if not s.startswith("--"):
            break
        s = s[2:].strip()
        if s.lower().startswith("indexes:"):
            continue
        lines.append(s)
    return " ".join(lines)


def write_kpi_dictionary(path: Path = DOCS / "kpi-dictionary.md") -> Path:
    kpis = load_kpis()
    t = kpi_table(kpis)
    out = ["# KPI dictionary", "",
           "_Generated from `config/kpis.yaml` by `python -m flowsight docs` - edit the YAML, not this file._", "",
           "| Tier | KPI | Definition | Formula | Target | Status rule | Owner |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    order = {"north_star": 0, "driver": 1, "input": 2, "health": 3}
    for _, r in t.sort_values(by="tier", key=lambda s: s.map(order)).iterrows():
        cell = lambda x: str(x).replace("|", "\\|")  # noqa: E731
        out.append(f"| {r.tier.replace('_', ' ')} | **{r['name']}** (`{r.kpi_id}`) | {cell(r.definition)} | "
                   f"{cell(r.formula)} | {cell(r.target_rule)} | {cell(r.rag_rule)} | {r.owner} |")
    out += ["", "## SQL", "", "Each KPI runs this SQL unchanged on SQLite and Spark.", ""]
    for k in kpis:
        out += [f"### {k.name}", "", "```sql", k.sql.strip(), "```", ""]
    path.write_text("\n".join(out), encoding="utf-8")
    return path


def write_data_dictionary(engine, path: Path = DOCS / "data-dictionary.md") -> list[str]:
    glossary = yaml.safe_load(GLOSSARY.read_text()) if GLOSSARY.exists() else {}
    cols_doc = glossary.get("columns", {})
    missing = []
    out = ["# Data dictionary", "",
           "_Generated by `python -m flowsight docs` from the SQL models and `config/glossary.yaml`._", "",
           "Layers: **silver** = cleaned, typed, de-duplicated source data; **gold** = business marts; "
           "**features** = model inputs (columns starting `y_` / `t_` look forward and are labels only).", ""]
    for m in topo_sort(discover_models()):
        df = engine.query(f"SELECT * FROM {m.name} LIMIT 200")
        n = engine.row_count(m.name)
        out += [f"## `{m.name}` ({m.layer})", "", _header_comment(m.sql) or "", "",
                f"Rows: {n:,} · built from: {', '.join(sorted(m.deps)) or 'raw files'}", "",
                "| Column | Type | Description |", "| --- | --- | --- |"]
        for c in df.columns:
            kind = "number" if pd.api.types.is_numeric_dtype(df[c]) else "text"
            desc = cols_doc.get(c)
            if desc is None:
                missing.append(f"{m.name}.{c}")
                desc = "**undocumented**"
            out.append(f"| `{c}` | {kind} | {desc} |")
        out.append("")
    path.write_text("\n".join(out), encoding="utf-8")
    return missing


def write_docs(engine, log=print) -> list[str]:
    write_kpi_dictionary()
    missing = write_data_dictionary(engine)
    log(f"  docs/kpi-dictionary.md, docs/data-dictionary.md written"
        + (f" - {len(missing)} undocumented columns: {', '.join(missing[:8])}" if missing else " - every column documented"))
    return missing


def columns_in_models(engine) -> list[str]:
    cols = set()
    for m in discover_models():
        cols.update(engine.query(f"SELECT * FROM {m.name} LIMIT 1").columns)
    return sorted(cols)


