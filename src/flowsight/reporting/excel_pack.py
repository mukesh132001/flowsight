"""Monthly distribution KPI pack (Excel). Totals, variances and attainment are live formulas,
the scorecard has 13-month sparklines, and the charts are native Excel charts."""
from __future__ import annotations

from pathlib import Path

import xlsxwriter
from xlsxwriter.utility import xl_rowcol_to_cell

from .theme import COLORS, RAG_LABEL

FMT_USD_M = '$#,##0.0,,"M";-$#,##0.0,,"M"'
FMT_USD_B = '$#,##0.00,,,"B"'
FMT_PCT = '0.0%'
FMT_INT = '#,##0'


def _num_fmt(unit: str) -> str:
    return {"usd": FMT_USD_M, "pct": FMT_PCT, "count": '#,##0.0', "ratio": '0.00'}.get(unit, '0.00')


def build_excel(model: dict, path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb = xlsxwriter.Workbook(path)
    wb.set_properties({"title": f"FlowSight distribution KPI pack - {model['as_of_label']}",
                       "author": "FlowSight", "comments": "Fictional firm, synthetic data"})
    base = {"font_name": "Segoe UI", "font_size": 10, "valign": "vcenter"}
    F = lambda **k: wb.add_format({**base, **k})  # noqa: E731
    title = F(bold=True, font_size=16, font_color=COLORS["ink"])
    sub = F(font_color=COLORS["ink_2"], italic=True)
    head = F(bold=True, font_color="#ffffff", bg_color=COLORS["header"], border=0, text_wrap=True)
    txt = F(font_color=COLORS["ink"], text_wrap=True)
    txt_nw = F(font_color=COLORS["ink"])
    muted = F(font_color=COLORS["ink_2"], text_wrap=True)
    usd = F(num_format=FMT_USD_M)
    usd_b = F(num_format=FMT_USD_B)
    pct = F(num_format=FMT_PCT)
    integer = F(num_format=FMT_INT)
    total_usd = F(num_format=FMT_USD_M, bold=True, top=1)
    total_lbl = F(bold=True, top=1)
    rag_fmt = {k: F(bold=True, font_color=v["text"], bg_color=v["fill"]) for k, v in COLORS["rag"].items()}

    # ---------------------------------------------------------------- Summary
    ws = wb.add_worksheet("Summary")
    ws.hide_gridlines(2)
    ws.set_column("A:A", 34)
    ws.set_column("B:G", 13)
    ws.set_column("H:H", 16)
    ws.set_column("I:I", 30)
    ws.write("A1", f"Distribution KPI pack - {model['as_of_label']}", title)
    ws.write("A2", f"{model['firm']} (fictional) · generated by FlowSight from synthetic data", sub)
    ws.write("A4", "What happened", F(bold=True, font_size=12))
    row = 4
    for b in model["commentary"]:
        ws.merge_range(row, 0, row, 8, f"•  {b}", txt)
        ws.set_row(row, 15 * (len(b) // 150 + 1) + 4)
        row += 1
    row += 1
    hdr = ["KPI", "Value", "Prior month", "Change", "Target", "Status", "Year ago", "13-month trend", "Owner"]
    ws.write_row(row, 0, hdr, head)
    ws.set_row(row, 28)
    trends = wb.add_worksheet("Trends")
    trends.write_row(0, 0, ["KPI"] + [f"t-{12 - i}" if i < 12 else "now" for i in range(13)], head)
    first = row + 1
    for i, k in enumerate(model["scorecard"]):
        r = first + i
        nf = F(num_format=_num_fmt(k["unit"]))
        ws.write(r, 0, k["name"], txt_nw)
        ws.write_number(r, 1, k["value"], nf) if k["value"] is not None else ws.write_blank(r, 1, None)
        if k["prior_value"] is not None:
            ws.write_number(r, 2, k["prior_value"], nf)
            ws.write_formula(r, 3, f"={xl_rowcol_to_cell(r, 1)}-{xl_rowcol_to_cell(r, 2)}", nf,
                             k["value"] - k["prior_value"])
        if k["target"] is not None:
            ws.write_number(r, 4, k["target"], nf)
        ws.write(r, 5, RAG_LABEL[k["rag"]], rag_fmt[k["rag"]])
        if k["yoy_value"] is not None:
            ws.write_number(r, 6, k["yoy_value"], nf)
        ws.write(r, 8, k["owner"], muted)
        trends.write(i + 1, 0, k["name"])
        series = k["trend_13m"]
        trends.write_row(i + 1, 1 + (13 - len(series)), series)
        ws.add_sparkline(r, 7, {"range": f"Trends!B{i + 2}:N{i + 2}", "type": "line",
                                "series_color": COLORS["series"][0], "markers": False,
                                "last_point": True, "markers_color": COLORS["series"][0]})
    trends.set_column("A:A", 34)
    trends.hide()
    ws.freeze_panes(first, 1)

    # ---------------------------------------------------------------- Monthly flows
    mf = wb.add_worksheet("Monthly flows")
    mf.set_column("A:A", 11)
    mf.set_column("B:J", 14)
    mf.write("A1", "Flows and AUM by month (transfer agent, all funds)", title)
    cols = ["Month", "Gross sales", "Redemptions", "Net flows", "Plan", "Vs plan", "Market & FX",
            "Ending AUM", "Organic growth (ann.)", "Fee run rate"]
    mf.write_row(2, 0, cols, head)
    mf.set_row(2, 30)
    rows = model["monthly"]
    for i, m in enumerate(rows):
        r = 3 + i
        c = lambda col: xl_rowcol_to_cell(r, col)  # noqa: E731
        mf.write(r, 0, m["month"])
        mf.write_number(r, 1, m["gross_sales"], usd)
        mf.write_number(r, 2, m["redemptions"], usd)
        mf.write_formula(r, 3, f"={c(1)}-{c(2)}", usd, m["net_flows"])
        if m["plan_net_flows"] is not None:
            mf.write_number(r, 4, m["plan_net_flows"], usd)
            mf.write_formula(r, 5, f"={c(3)}-{c(4)}", usd, m["net_flows"] - m["plan_net_flows"])
        mf.write_number(r, 6, m["market_effect"], usd)
        mf.write_number(r, 7, m["ending_aum"], usd_b)
        prev_aum = f"{xl_rowcol_to_cell(r - 1, 7)}" if i else f"({c(7)}-{c(3)}-{c(6)})"
        mf.write_formula(r, 8, f"=IFERROR({c(3)}*12/{prev_aum},\"\")", pct, m["organic_growth"] or 0)
        mf.write_number(r, 9, m["revenue_run_rate"], usd)
    last = 3 + len(rows) - 1
    tr = last + 1
    mf.write(tr, 0, "Total", total_lbl)
    for col, key in ((1, "gross_sales"), (2, "redemptions"), (3, "net_flows"), (6, "market_effect")):
        mf.write_formula(tr, col, f"=SUM({xl_rowcol_to_cell(3, col)}:{xl_rowcol_to_cell(last, col)})", total_usd,
                         sum(m[key] for m in rows))
    mf.conditional_format(3, 5, last, 5, {"type": "cell", "criteria": "<", "value": 0,
                                         "format": F(font_color=COLORS["rag"]["RED"]["text"])})
    ch = wb.add_chart({"type": "column"})
    ch.add_series({"name": "Net flows", "categories": ["Monthly flows", 3, 0, last, 0],
                   "values": ["Monthly flows", 3, 3, last, 3],
                   "fill": {"color": COLORS["series"][0]}, "invert_if_negative": True,
                   "invert_if_negative_color": COLORS["negative"], "gap": 80})
    ch.set_title({"name": "Net flows by month", "name_font": {"size": 12, "bold": True}})
    ch.set_legend({"none": True})
    ch.set_y_axis({"num_format": '$#,##0,,"M"', "major_gridlines": {"visible": True, "line": {"color": COLORS["grid"]}}})
    ch.set_x_axis({"num_font": {"rotation": -45}})
    ch.set_size({"width": 760, "height": 300})
    mf.insert_chart(tr + 2, 0, ch)
    ca = wb.add_chart({"type": "line"})
    ca.add_series({"name": "Ending AUM", "categories": ["Monthly flows", 3, 0, last, 0],
                   "values": ["Monthly flows", 3, 7, last, 7], "line": {"color": COLORS["series"][0], "width": 2}})
    ca.set_title({"name": "AUM", "name_font": {"size": 12, "bold": True}})
    ca.set_legend({"none": True})
    ca.set_y_axis({"num_format": '$#,##0,,,"B"', "major_gridlines": {"visible": True, "line": {"color": COLORS["grid"]}}})
    ca.set_size({"width": 760, "height": 260})
    mf.insert_chart(tr + 18, 0, ca)
    mf.freeze_panes(3, 1)

    # ---------------------------------------------------------------- Families + funds
    fs = wb.add_worksheet("Products")
    fs.set_column("A:A", 40)
    fs.set_column("B:G", 14)
    fs.write("A1", f"Product families - year to date {model['as_of_label'][-4:]}", title)
    fs.write_row(2, 0, ["Family", "Gross sales", "Redemptions", "Net flows", "AUM", "Share of AUM"], head)
    fams = model["families"]
    for i, f in enumerate(fams):
        r = 3 + i
        fs.write(r, 0, f["family"])
        fs.write_number(r, 1, f["gross_sales"], usd)
        fs.write_number(r, 2, f["redemptions"], usd)
        fs.write_formula(r, 3, f"={xl_rowcol_to_cell(r, 1)}-{xl_rowcol_to_cell(r, 2)}", usd, f["net_flows_ytd"])
        fs.write_number(r, 4, f["aum"], usd)
        fs.write_formula(r, 5, f"={xl_rowcol_to_cell(r, 4)}/SUM($E$4:$E${3 + len(fams)})", pct,
                         f["aum"] / sum(x["aum"] for x in fams))
    fl = 3 + len(fams)
    fs.write(fl, 0, "Total", total_lbl)
    for col, key in ((1, "gross_sales"), (2, "redemptions"), (3, "net_flows_ytd"), (4, "aum")):
        fs.write_formula(fl, col, f"=SUM({xl_rowcol_to_cell(3, col)}:{xl_rowcol_to_cell(fl - 1, col)})", total_usd,
                         sum(x[key] for x in fams))
    cb = wb.add_chart({"type": "bar"})
    cb.add_series({"name": "Net flows YTD", "categories": ["Products", 3, 0, fl - 1, 0],
                   "values": ["Products", 3, 3, fl - 1, 3], "fill": {"color": COLORS["series"][0]},
                   "invert_if_negative": True, "invert_if_negative_color": COLORS["negative"], "gap": 60})
    cb.set_title({"name": "Net flows by family (YTD)", "name_font": {"size": 12, "bold": True}})
    cb.set_legend({"none": True})
    cb.set_y_axis({"reverse": True})
    cb.set_x_axis({"num_format": '$#,##0,,"M"', "major_gridlines": {"visible": True, "line": {"color": COLORS["grid"]}}})
    cb.set_size({"width": 640, "height": 300})
    fs.insert_chart(fl + 2, 0, cb)
    fr = fl + 19
    fs.write(fr, 0, "Funds - last 12 months", F(bold=True, font_size=12))
    fs.write_row(fr + 1, 0, ["Fund", "Family", "Vehicle", "AUM", "Net flows 12m", "Organic growth 12m",
                             "Excess return 3m"], head)
    for i, f in enumerate(model["funds"]):
        r = fr + 2 + i
        fs.write(r, 0, f["fund"])
        fs.write(r, 1, f["family"], muted)
        fs.write(r, 2, f["vehicle"])
        fs.write_number(r, 3, f["aum"], usd)
        fs.write_number(r, 4, f["net_flows_12m"], usd)
        if f["organic_growth_12m"] is not None:
            fs.write_number(r, 5, f["organic_growth_12m"], pct)
        if f["excess_3m"] is not None:
            fs.write_number(r, 6, f["excess_3m"], pct)
    end = fr + 1 + len(model["funds"])
    fs.conditional_format(fr + 2, 4, end, 4, {"type": "data_bar", "bar_color": COLORS["series"][0],
                                              "bar_negative_color": COLORS["negative"], "bar_solid": True})

    # ---------------------------------------------------------------- Territories heatmap
    th = wb.add_worksheet("Territories")
    th.set_column("A:A", 18)
    th.set_column(1, 13, 10)
    th.write("A1", "Net flows by territory (last 12 months, intermediary feeds)", title)
    hm = model["heatmap"]
    th.write_row(2, 0, ["Territory"] + hm["months"] + ["Total"], head)
    for i, r_ in enumerate(hm["rows"]):
        r = 3 + i
        th.write(r, 0, r_["territory"])
        th.write_row(r, 1, r_["values"], usd)
        th.write_formula(r, 13, f"=SUM({xl_rowcol_to_cell(r, 1)}:{xl_rowcol_to_cell(r, 12)})", total_usd,
                         sum(r_["values"]))
    lr = 2 + len(hm["rows"])
    th.conditional_format(3, 1, lr, 12, {"type": "3_color_scale", "min_color": COLORS["div_neg"],
                                         "mid_type": "num", "mid_value": 0, "mid_color": COLORS["div_mid"],
                                         "max_color": COLORS["div_pos"]})
    th.write(lr + 2, 0, "Blue = net inflows, red = net outflows, gray = about zero.", muted)

    # ---------------------------------------------------------------- Wholesalers
    wsh = wb.add_worksheet("Sales team")
    wsh.set_column("A:A", 22)
    wsh.set_column("B:D", 12)
    wsh.set_column("E:K", 13)
    wsh.write("A1", f"Wholesaler scorecard - {model['quarter']} to date", title)
    wsh.write_row(2, 0, ["Wholesaler", "Role", "Territory", "Group", "Meetings", "Calls", "Advisors touched",
                         "Credited gross", "Goal (QTD)", "Attainment", "Conversion (3m)"], head)
    wsh.set_row(2, 30)
    for i, w in enumerate(model["wholesalers"]):
        r = 3 + i
        wsh.write(r, 0, w["wholesaler_name"])
        wsh.write(r, 1, w["role"])
        wsh.write(r, 2, w["territory"])
        wsh.write(r, 3, w["channel_group"])
        wsh.write_number(r, 4, w["meetings"], integer)
        wsh.write_number(r, 5, w["calls"], integer)
        wsh.write_number(r, 6, w["advisors_touched"], integer)
        wsh.write_number(r, 7, w["credited_gross"], usd)
        if w["goal"]:
            wsh.write_number(r, 8, w["goal"], usd)
            wsh.write_formula(r, 9, f"=IFERROR({xl_rowcol_to_cell(r, 7)}/{xl_rowcol_to_cell(r, 8)},\"\")", pct,
                              w["credited_gross"] / w["goal"])
        if w.get("conversion") is not None:
            wsh.write_number(r, 10, w["conversion"], pct)
    end = 2 + len(model["wholesalers"])
    wsh.conditional_format(3, 9, end, 9, {"type": "data_bar", "bar_color": COLORS["series"][0], "bar_solid": True,
                                          "min_type": "num", "min_value": 0, "max_type": "num", "max_value": 1.5})
    wsh.autofilter(2, 0, end, 10)
    wsh.freeze_panes(3, 1)

    # ---------------------------------------------------------------- Call lists
    cl = wb.add_worksheet("Call lists")
    cl.set_column("A:A", 20)
    cl.set_column("B:B", 6)
    cl.set_column("C:D", 22)
    cl.set_column("E:E", 30)
    cl.set_column("F:I", 12)
    cl.set_column("J:J", 90)
    cl.write("A1", f"Next-best-action call lists for {model['as_of_label']} (ranked by expected incremental sales)", title)
    cl.write_row(2, 0, ["Wholesaler", "Rank", "Advisor", "Firm", "Product family", "Book", "P(buy) no meeting",
                        "P(buy) with meeting", "Expected incremental", "Why"], head)
    cl.set_row(2, 30)
    for i, r_ in enumerate(model["recommendations"]):
        r = 3 + i
        cl.write(r, 0, r_["wholesaler_name"])
        cl.write_number(r, 1, r_["rank"], integer)
        cl.write(r, 2, r_["advisor_name"])
        cl.write(r, 3, r_["firm_name"])
        cl.write(r, 4, r_["family_name"])
        cl.write_number(r, 5, r_["book_aum_est"], usd)
        cl.write_number(r, 6, r_["p_if_not_met"], pct)
        cl.write_number(r, 7, r_["p_if_met"], pct)
        cl.write_number(r, 8, r_["exp_value"], usd)
        cl.write(r, 9, r_["reasons"].replace(" | ", "; "), muted)
    cl.autofilter(2, 0, 2 + len(model["recommendations"]), 9)
    cl.freeze_panes(3, 2)

    # ---------------------------------------------------------------- Retention
    rt = wb.add_worksheet("Retention watchlist")
    rt.set_column("A:B", 22)
    rt.set_column("C:C", 26)
    rt.set_column("D:G", 13)
    rt.set_column("H:H", 90)
    rt.write("A1", "Redemption early warning - advisors most likely to pull 25%+ of assets in the next 3 months", title)
    rt.write_row(2, 0, ["Advisor", "Wholesaler", "Firm", "Assets with us", "Risk", "AUM at risk",
                        "Months since contact", "Why"], head)
    for i, r_ in enumerate(model["watchlist"]):
        r = 3 + i
        rt.write(r, 0, r_["advisor_name"])
        rt.write(r, 1, r_["wholesaler_name"] or "-")
        rt.write(r, 2, r_["firm_name"])
        rt.write_number(r, 3, r_["aum"], usd)
        rt.write_number(r, 4, r_["risk_score"], pct)
        rt.write_formula(r, 5, f"={xl_rowcol_to_cell(r, 3)}*{xl_rowcol_to_cell(r, 4)}", usd,
                         r_["aum"] * r_["risk_score"])
        rt.write_number(r, 6, r_["months_since_contact"], integer)
        rt.write(r, 7, r_["reasons"].replace(" | ", "; "), muted)
    rt.freeze_panes(3, 1)

    # ---------------------------------------------------------------- Data quality
    dq = wb.add_worksheet("Data quality")
    dq.set_column("A:A", 34)
    dq.set_column("B:D", 12)
    dq.set_column("E:E", 100)
    dq.write("A1", "Data-quality checks (run on every pipeline refresh)", title)
    dq.write_row(2, 0, ["Check", "Severity", "Failing rows", "Status", "Rule"], head)
    status_map = {"PASS": "GREEN", "WARN": "AMBER", "FAIL": "RED"}
    for i, c in enumerate(model["dq"]):
        r = 3 + i
        dq.write(r, 0, c["check_name"])
        dq.write(r, 1, c["severity"])
        dq.write_number(r, 2, c["failing_rows"], integer)
        dq.write(r, 3, c["status"], rag_fmt[status_map[c["status"]]])
        dq.write(r, 4, c["description"], muted)
    r0 = 5 + len(model["dq"])
    dq.write(r0, 0, "Unattributed sales by month", F(bold=True, font_size=12))
    dq.write_row(r0 + 1, 0, ["Month", "Unattributed"], head)
    for i, u in enumerate(model["unattributed"]):
        dq.write(r0 + 2 + i, 0, u["month"])
        dq.write_number(r0 + 2 + i, 1, u["value"], pct)
    ul = r0 + 1 + len(model["unattributed"])
    cu = wb.add_chart({"type": "line"})
    cu.add_series({"name": "Unattributed sales", "categories": ["Data quality", r0 + 2, 0, ul, 0],
                   "values": ["Data quality", r0 + 2, 1, ul, 1], "line": {"color": COLORS["series"][0], "width": 2}})
    cu.set_title({"name": "Share of sales with an unmapped rep code (threshold 3%)", "name_font": {"size": 11}})
    cu.set_legend({"none": True})
    cu.set_y_axis({"num_format": "0%", "major_gridlines": {"visible": True, "line": {"color": COLORS["grid"]}}})
    cu.set_size({"width": 640, "height": 260})
    dq.insert_chart(r0 + 1, 3, cu)
    for sheet in wb.worksheets():
        sheet.set_landscape()
        sheet.fit_to_pages(1, 0)
        sheet.set_paper(1)
    wb.close()
    return path
